function getToursForCountry(countryId) {
  const city = TOUR_DATA.cityTours.filter(t => t.country === countryId);
  const multi = TOUR_DATA.countryTours.filter(t => t.country === countryId);
  return { cityTours: city, countryTours: multi };
}

// Helper: get multi-country tour by id
function getMultiCountryTour(id) {
  return TOUR_DATA.multiCountryTours.find(t => t.id === id);
}

// Helper: convert lat/lon to SVG x/y within a given viewBox
// Bounding box for Southern Africa region: lon 10–40, lat -35 to -8
function geoToSVG(lat, lon, viewBox = { minLon: 10, maxLon: 42, minLat: -35.5, maxLat: -8, width: 800, height: 700 }) {
  const x = ((lon - viewBox.minLon) / (viewBox.maxLon - viewBox.minLon)) * viewBox.width;
  const y = ((viewBox.maxLat - lat) / (viewBox.maxLat - viewBox.minLat)) * viewBox.height;
  return { x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
}

